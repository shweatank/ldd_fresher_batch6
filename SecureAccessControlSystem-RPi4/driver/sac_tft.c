/* --- Low-level ILI9225 register/SPI helpers --- */

static int ili9225_write16(struct sac_device *sac, u16 value)
{
	u8 buf[2];
	buf[0] = value >> 8;
	buf[1] = value & 0xFF;
	return spi_write(sac->tft_spi, buf, 2);
}

static void ili9225_write_reg(struct sac_device *sac, u16 reg, u16 data)
{
	gpiod_set_value_cansleep(sac->tft_dc, 0);
	ili9225_write16(sac, reg);
	gpiod_set_value_cansleep(sac->tft_dc, 1);
	ili9225_write16(sac, data);
}

static void ili9225_reset(struct sac_device *sac)
{
	if (!sac->tft_rst)
		return;
	gpiod_set_value_cansleep(sac->tft_rst, 1);
	msleep(5);
	gpiod_set_value_cansleep(sac->tft_rst, 0);
	msleep(20);
	gpiod_set_value_cansleep(sac->tft_rst, 1);
	msleep(50);
}

/* --- Drawing primitives (landscape coordinates) --- */

static void draw_pixel(struct sac_device *sac, int x, int y, u16 color)
{
	int px, py;

	if (x < 0 || x >= LAND_W || y < 0 || y >= LAND_H)
		return;

	/* Landscape mapping to panel-native portrait GRAM coordinates. */
	px = y;
	py = SCREEN_HEIGHT - 1 - x;

	gpiod_set_value_cansleep(sac->tft_dc, 0);
	ili9225_write16(sac, 0x20);
	gpiod_set_value_cansleep(sac->tft_dc, 1);
	ili9225_write16(sac, px);

	gpiod_set_value_cansleep(sac->tft_dc, 0);
	ili9225_write16(sac, 0x21);
	gpiod_set_value_cansleep(sac->tft_dc, 1);
	ili9225_write16(sac, py);

	gpiod_set_value_cansleep(sac->tft_dc, 0);
	ili9225_write16(sac, 0x22);
	gpiod_set_value_cansleep(sac->tft_dc, 1);
	ili9225_write16(sac, color);
}

static void fill_landscape(struct sac_device *sac, u16 color)
{
	int x, y;
	for (y = 0; y < LAND_H; y++)
		for (x = 0; x < LAND_W; x++)
			draw_pixel(sac, x, y, color);
}

static void draw_char(struct sac_device *sac, int x, int y, char c, u16 color)
{
	const uint8_t *bitmap;
	int row, col;

	if (c < 32 || c > 127)
		return;
	bitmap = font8x8_basic[c - 32];

	for (row = 0; row < 8; row++) {
		for (col = 0; col < 8; col++) {
			if (bitmap[row] & (1 << (7 - col))) {
				draw_pixel(sac, x + col * TEXT_SCALE, y + row * TEXT_SCALE, color);
				draw_pixel(sac, x + col * TEXT_SCALE + 1, y + row * TEXT_SCALE, color);
				draw_pixel(sac, x + col * TEXT_SCALE, y + row * TEXT_SCALE + 1, color);
				draw_pixel(sac, x + col * TEXT_SCALE + 1, y + row * TEXT_SCALE + 1, color);
			}
		}
	}
}

static void draw_centered_line(struct sac_device *sac, const char *line, int y)
{
	int i, len = 0, x;

	while (line[len] && len < 13)
		len++;

	x = (LAND_W - (len * 16)) / 2;
	if (x < 0)
		x = 0;

	for (i = 0; i < len; i++)
		draw_char(sac, x + (i * 16), y, line[i], 0x0000);
}

static void draw_string(struct sac_device *sac, const char *str)
{
	char wrapped[8][16];
	int line_idx = 0, char_idx = 0;
	int i;
	int y = 16;
	int line_step = 24;

	memset(wrapped, 0, sizeof(wrapped));

	for (i = 0; str[i] && line_idx < 8; i++) {
		if (str[i] == '\n') {
			wrapped[line_idx][char_idx] = '\0';
			line_idx++;
			char_idx = 0;
			continue;
		}

		if (char_idx >= 13) {
			wrapped[line_idx][char_idx] = '\0';
			line_idx++;
			char_idx = 0;
			if (line_idx >= 8)
				break;
		}

		wrapped[line_idx][char_idx++] = str[i];
	}
	if (line_idx < 8)
		wrapped[line_idx][char_idx] = '\0';

	/* Keep READY lower in middle on home screen. */
	if (strcmp(str, "SECURE ACCESS\nREADY") == 0)
		line_step = 60;

	for (i = 0; i <= line_idx && i < 8; i++) {
		if (wrapped[i][0] == '\0')
			continue;
		draw_centered_line(sac, wrapped[i], y);
		y += line_step;
	}
}

/* Controller init sequence + first paint (called from probe). */
int sac_tft_init(struct sac_device *sac)
{
	if (!sac->tft_spi)
		return -ENODEV;

	ili9225_reset(sac);

	ili9225_write_reg(sac, 0x01, 0x011C);
	ili9225_write_reg(sac, 0x02, 0x0100);
	ili9225_write_reg(sac, 0x03, 0x1018);
	ili9225_write_reg(sac, 0x08, 0x0808);
	ili9225_write_reg(sac, 0x0F, 0x0B01);
	ili9225_write_reg(sac, 0x10, 0x0A00);
	ili9225_write_reg(sac, 0x11, 0x1038);
	msleep(50);
	ili9225_write_reg(sac, 0x12, 0x1121);
	ili9225_write_reg(sac, 0x13, 0x0063);
	ili9225_write_reg(sac, 0x14, 0x5A00);
	msleep(50);
	ili9225_write_reg(sac, 0x07, 0x1017);

	mutex_lock(&sac->io_lock);
	fill_landscape(sac, 0xFFFF);
	draw_string(sac, "SECURE ACCESS\nREADY");
	mutex_unlock(&sac->io_lock);

	return 0;
}

/* Full-screen status update used after each auth state transition. */
void sac_tft_print_status(struct sac_device *sac, const char *msg)
{
	if (!sac->tft_spi)
		return;

	mutex_lock(&sac->io_lock);
	/* Clear full frame once, then draw exactly one state message. */
	fill_landscape(sac, 0xFFFF);
	draw_string(sac, msg);
	mutex_unlock(&sac->io_lock);

	dev_info(sac->dev, "ILI9225 status: %s\n", msg);
}

void sac_tft_show_authenticating(struct sac_device *sac)
{
	sac_tft_print_status(sac, "AUTHENTICATING...");
}

/* Blank white frame (app exit ioctl). */
void sac_tft_clear(struct sac_device *sac)
{
	if (!sac->tft_spi)
		return;

	mutex_lock(&sac->io_lock);
	fill_landscape(sac, 0xFFFF);
	mutex_unlock(&sac->io_lock);
}

void sac_tft_set_style(struct sac_device *sac, u16 fg, u16 bg, u8 scale)
{
	(void)sac; (void)fg; (void)bg; (void)scale;
}

/* --- GPIO-attached LEDs (overlay optional-gpios) --- */

void sac_leds_locked_alert(struct sac_device *sac)
{
	int i;
	if (sac->green_led)
		gpiod_set_value_cansleep(sac->green_led, 0);

	for (i = 0; i < 2; i++) {
		if (sac->red_led)
			gpiod_set_value_cansleep(sac->red_led, 1);
		msleep(80);
		if (sac->red_led)
			gpiod_set_value_cansleep(sac->red_led, 0);
		msleep(80);
	}
}

void sac_leds_result(struct sac_device *sac, bool ok)
{
	int i;

	/* Blink success/failure LED for ~2 seconds (10 x 200ms). */
	for (i = 0; i < 10; i++) {
		if (ok && sac->green_led)
			gpiod_set_value_cansleep(sac->green_led, 1);
		if (!ok && sac->red_led)
			gpiod_set_value_cansleep(sac->red_led, 1);
		msleep(100);
		if (ok && sac->green_led)
			gpiod_set_value_cansleep(sac->green_led, 0);
		if (!ok && sac->red_led)
			gpiod_set_value_cansleep(sac->red_led, 0);
		msleep(100);
	}
}
